#!/usr/bin/env bash
# Run representative short workloads across fresh Lima VM boots.
#
# Usage: bench/run-v2-workloads.sh [output-directory]
# Environment: SESSIONS (default 3), RUNS (40), WARMUPS (5), GAP_MS (100),
#              NET_RUNS (15), NET_WARMUPS (3), NET_GAP_MS (1000),
#              SEED (20261021), BOOT_SETTLE_S (20), LIMA_INSTANCE (kiln).
set -euo pipefail

ROOT=$(git rev-parse --show-toplevel)
cd "$ROOT"

OUT=${1:-bench/results/v2/macbook-air-2026-10-11/workloads}
SESSIONS=${SESSIONS:-3}
RUNS=${RUNS:-40}
WARMUPS=${WARMUPS:-5}
GAP_MS=${GAP_MS:-100}
NET_RUNS=${NET_RUNS:-15}
NET_WARMUPS=${NET_WARMUPS:-3}
NET_GAP_MS=${NET_GAP_MS:-1000}
SEED=${SEED:-20261021}
BOOT_SETTLE_S=${BOOT_SETTLE_S:-20}
LIMA_INSTANCE=${LIMA_INSTANCE:-kiln}
workloads=(shell python node fs dns http)

if [[ -e "$OUT" ]]; then
    echo "$OUT already exists; choose a new output directory" >&2
    exit 2
fi
mkdir -p "$OUT"

for ((n = 1; n <= SESSIONS; n++)); do
    label=$(printf 'workload-boot-%02d' "$n")
    echo "[$label] restarting $LIMA_INSTANCE" >&2
    limactl stop "$LIMA_INSTANCE"
    limactl start "$LIMA_INSTANCE"
    sleep "$BOOT_SETTLE_S"

    # Rotate the block order across boots. Runtime order inside each block is a
    # randomized Latin square generated by v2.py.
    shift_by=$(( (n - 1) * 2 % ${#workloads[@]} ))
    for ((i = 0; i < ${#workloads[@]}; i++)); do
        workload=${workloads[$(( (i + shift_by) % ${#workloads[@]} ))]}
        runs=$RUNS
        warmups=$WARMUPS
        gap=$GAP_MS
        if [[ "$workload" == dns || "$workload" == http ]]; then
            runs=$NET_RUNS
            warmups=$NET_WARMUPS
            gap=$NET_GAP_MS
        fi
        echo "[$label/$workload] $runs measured rounds" >&2
        limactl shell --workdir "$ROOT" "$LIMA_INSTANCE" -- \
            sudo python3 -I bench/v2.py latency \
            --config bench/v2-workloads.json \
            --out "$OUT/$label-$workload" \
            --session "$label" \
            --runs "$runs" \
            --warmups "$warmups" \
            --gap-ms "$gap" \
            --case "-$workload\$" \
            --seed "$((SEED + n * 100 + i))"
    done
done

for workload in "${workloads[@]}"; do
    python3 -I bench/v2.py summarize "$OUT"/workload-boot-*-$workload \
        --out "$OUT/summary-$workload" \
        --baseline "kiln-$workload" \
        --bootstrap-seed "$SEED"
done

echo "representative workload campaign complete: $OUT" >&2
