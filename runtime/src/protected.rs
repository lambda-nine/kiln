//! The protected-path contract: which parts of a run's upper layer belong to
//! the runtime rather than the sandbox, and what a checkpoint may contain
//! there. kiln's own setup code takes its mount targets from these constants,
//! so the contract cannot silently drift from what kiln mounts.
//!
//! A checkpoint walker classifies every raw-upper entry with [`check`]. An
//! upper must not replace, whiteout or redirect a runtime mount target or one
//! of its ancestors, nor make one opaque (that would hide the image's mount
//! scaffolding). Nothing may exist beneath a mount target: those trees are
//! covered by runtime mounts and recreated by every new sandbox. Runtime-
//! generated entries are excluded from capture and regenerated on restore.
//! Everything else is ordinary sandbox data.

/// Mount targets inside the merged root, in the order kiln mounts them. /dev
/// is a tmpfs: the device binds, its symlinks and /dev/shm live inside that
/// tmpfs, never in the upper.
pub const DEV: &str = "/dev";
pub const PROC: &str = "/proc";
pub const CGROUP: &str = "/sys/fs/cgroup";
pub const MOUNT_TARGETS: [&str; 3] = [DEV, PROC, CGROUP];

/// Host devices bound into the /dev tmpfs.
pub const DEVICES: [&str; 6] = ["null", "zero", "full", "random", "urandom", "tty"];
/// Symlinks kiln creates in the /dev tmpfs, with their targets.
pub const DEV_LINKS: [(&str, &str); 4] =
    [("fd", "/proc/self/fd"), ("stdin", "/proc/self/fd/0"), ("stdout", "/proc/self/fd/1"), ("stderr", "/proc/self/fd/2")];
/// The POSIX shared-memory tmpfs inside /dev. Default scratch, never persistent.
pub const DEV_SHM: &str = "/dev/shm";

/// Written by kiln as host root when the network plan has DNS. Host-root
/// ownership (unmapped) is expected for exactly this entry.
pub const RESOLV_CONF: &str = "/etc/resolv.conf";

/// Every mount point visible inside a running sandbox, root first.
pub fn runtime_mounts() -> Vec<String> {
    let mut mounts = vec!["/".to_owned(), DEV.to_owned()];
    mounts.extend(DEVICES.iter().map(|d| format!("{DEV}/{d}")));
    mounts.push(DEV_SHM.to_owned());
    mounts.push(PROC.to_owned());
    mounts.push(CGROUP.to_owned());
    mounts
}

/// The proper ancestors of the mount targets, root included: "/", "/sys",
/// "/sys/fs".
pub fn ancestors() -> Vec<&'static str> {
    let mut out = vec!["/"];
    for target in MOUNT_TARGETS {
        let mut at = 0;
        while let Some(i) = target[at + 1..].find('/') {
            at += i + 1;
            let ancestor = &target[..at];
            if !out.contains(&ancestor) { out.push(ancestor); }
        }
    }
    out
}

/// What a checkpoint publishes as excluded from its persistent-overlay scope.
pub fn excluded_paths(generated: &[&str]) -> Vec<String> {
    let mut out: Vec<String> = [DEV, DEV_SHM, PROC, CGROUP].iter().map(|p| (*p).to_owned()).collect();
    out.extend(generated.iter().map(|p| (*p).to_owned()));
    out.sort();
    out.dedup();
    out
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// How the contract treats one sandbox path.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rule {
    /// Sandbox data.
    Ordinary,
    /// A mount target or one of its ancestors: if present in the upper it must
    /// be a plain, non-opaque directory. Only its directory metadata (mode,
    /// mapped owner, mtime, user xattrs) is captured.
    Scaffold,
    /// The parent of a generated entry (/etc): a directory if present, opaque
    /// allowed (it hides no runtime scaffolding).
    GeneratedParent,
    /// Generated by the runtime for this run; excluded and regenerated.
    Generated,
    /// Beneath a mount target: must not exist in the upper at all.
    Shadowed,
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// The kind of one raw-upper entry, as the walker classified it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    Directory { opaque: bool },
    /// A recognized overlay whiteout.
    Whiteout,
    Regular,
    Symlink,
    /// Anything else (the walker refuses most of these itself).
    Other,
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// What the walker does with an entry the contract accepts.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Disposition {
    Capture,
    /// Leave it out; the new sandbox regenerates it.
    Exclude,
}

/// A layout the contract refuses (`checkpoint_layout_unsupported`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LayoutError(pub String);

impl std::fmt::Display for LayoutError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "checkpoint_layout_unsupported: {}", self.0)
    }
}
impl std::error::Error for LayoutError {}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
fn is_beneath(path: &[u8], dir: &str) -> bool {
    path.len() > dir.len() && path.starts_with(dir.as_bytes()) && path[dir.len()] == b'/'
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// The rule for an absolute, normalized sandbox path (bytes: names need not
/// be UTF-8). `generated` is the run's recorded generated-entry list.
pub fn rule(path: &[u8], generated: &[&str]) -> Rule {
    if MOUNT_TARGETS.iter().any(|t| is_beneath(path, t)) { return Rule::Shadowed; }
    if MOUNT_TARGETS.iter().chain(ancestors().iter()).any(|t| t.as_bytes() == path) { return Rule::Scaffold; }
    if generated.iter().any(|g| g.as_bytes() == path) { return Rule::Generated; }
    if generated.iter().any(|g| g.rfind('/').is_some_and(|i| i > 0 && g.as_bytes()[..i] == *path)) {
        return Rule::GeneratedParent;
    }
    Rule::Ordinary
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// Classifies one raw-upper entry. Generated entries are excluded whatever
/// their kind; the restore regenerates them through no-follow paths.
pub fn check(path: &[u8], kind: Kind, generated: &[&str]) -> Result<Disposition, LayoutError> {
    let shown = String::from_utf8_lossy(path);
    match (rule(path, generated), kind) {
        (Rule::Ordinary, _) => Ok(Disposition::Capture),
        (Rule::Generated, _) => Ok(Disposition::Exclude),
        (Rule::Scaffold, Kind::Directory { opaque: false }) => Ok(Disposition::Capture),
        (Rule::Scaffold, Kind::Directory { opaque: true }) =>
            Err(LayoutError(format!("{shown} is runtime scaffolding and must not be opaque"))),
        (Rule::Scaffold, _) =>
            Err(LayoutError(format!("{shown} is runtime scaffolding and must remain a directory"))),
        (Rule::GeneratedParent, Kind::Directory { .. }) => Ok(Disposition::Capture),
        (Rule::GeneratedParent, _) =>
            Err(LayoutError(format!("{shown} holds a runtime-generated entry and must remain a directory"))),
        (Rule::Shadowed, _) =>
            Err(LayoutError(format!("{shown} is beneath a runtime mount and cannot be in the upper"))),
    }
}

// Consumed by the checkpoint walker (next milestone); pinned by the tests below.
#[allow(dead_code)]
/// Whether a requested writable path overlaps a reserved runtime subtree: it
/// equals, contains or lies beneath a mount target, or is a generated entry.
/// Default scratch /dev/shm overlaps by definition (it is a tmpfs).
pub fn writable_overlaps_reserved(path: &str, generated: &[&str]) -> bool {
    let p = path.as_bytes();
    MOUNT_TARGETS.iter().chain(generated.iter())
        .any(|t| t.as_bytes() == p || is_beneath(p, t) || is_beneath(t.as_bytes(), path))
}

/// The contract as stable text for other tools (`kiln checkpoint-contract`).
pub fn describe(generated: &[&str]) -> String {
    let mut text = String::from("kiln-protected-paths 1\n");
    for m in runtime_mounts() { text.push_str(&format!("mount {m}\n")); }
    for t in MOUNT_TARGETS { text.push_str(&format!("target {t}\n")); }
    for a in ancestors() { text.push_str(&format!("ancestor {a}\n")); }
    for g in generated { text.push_str(&format!("generated {g}\n")); }
    for e in excluded_paths(generated) { text.push_str(&format!("excluded {e}\n")); }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    const GEN: [&str; 1] = [RESOLV_CONF];

    #[test]
    fn mounts_targets_and_ancestors() {
        assert_eq!(runtime_mounts(), ["/", "/dev", "/dev/null", "/dev/zero", "/dev/full", "/dev/random",
            "/dev/urandom", "/dev/tty", "/dev/shm", "/proc", "/sys/fs/cgroup"]);
        assert_eq!(ancestors(), ["/", "/sys", "/sys/fs"]);
        assert_eq!(excluded_paths(&GEN), ["/dev", "/dev/shm", "/etc/resolv.conf", "/proc", "/sys/fs/cgroup"]);
        assert_eq!(excluded_paths(&[]), ["/dev", "/dev/shm", "/proc", "/sys/fs/cgroup"]);
    }

    #[test]
    fn every_rule() {
        use Kind::*;
        let ok = |p: &str, k| check(p.as_bytes(), k, &GEN);
        for p in ["/", "/sys", "/sys/fs", "/dev", "/proc", "/sys/fs/cgroup"] {
            assert_eq!(ok(p, Directory { opaque: false }), Ok(Disposition::Capture), "{p}");
            for bad in [Directory { opaque: true }, Whiteout, Regular, Symlink, Other] {
                assert!(ok(p, bad).is_err(), "{p} {bad:?}");
            }
        }
        for p in ["/dev/null", "/dev/shm", "/dev/shm/x", "/proc/1", "/sys/fs/cgroup/cgroup.procs"] {
            assert!(ok(p, Regular).unwrap_err().to_string().starts_with("checkpoint_layout_unsupported: "), "{p}");
            assert!(ok(p, Directory { opaque: false }).is_err(), "{p}");
        }
        assert_eq!(ok("/etc/resolv.conf", Regular), Ok(Disposition::Exclude));
        assert_eq!(ok("/etc/resolv.conf", Symlink), Ok(Disposition::Exclude));
        assert_eq!(ok("/etc", Directory { opaque: true }), Ok(Disposition::Capture));
        for bad in [Whiteout, Symlink, Regular] { assert!(ok("/etc", bad).is_err()); }
        // Without DNS, /etc and its resolv.conf are ordinary data.
        assert_eq!(check(b"/etc/resolv.conf", Regular, &[]), Ok(Disposition::Capture));
        assert_eq!(check(b"/etc", Symlink, &[]), Ok(Disposition::Capture));
        for p in ["/devices", "/dev2", "/proc1", "/sys/fsx", "/sys/other", "/sys/fs/cgroupx", "/etc/hosts",
            "/workspace/a", "/tmp"] {
            assert_eq!(ok(p, Regular), Ok(Disposition::Capture), "{p}");
            assert_eq!(ok(p, Whiteout), Ok(Disposition::Capture), "{p}");
        }
        assert_eq!(rule(b"/dev/\xff", &GEN), Rule::Shadowed);
        assert_eq!(rule(b"/w/\xff", &GEN), Rule::Ordinary);
    }

    #[test]
    fn writable_overlap() {
        for p in ["/dev", "/dev/shm", "/proc/sys", "/sys/fs/cgroup", "/sys", "/sys/fs", "/etc", "/etc/resolv.conf"] {
            assert!(writable_overlaps_reserved(p, &GEN), "{p}");
        }
        for p in ["/devx", "/data", "/sys/kernel", "/etc/ssl", "/workspace"] {
            assert!(!writable_overlaps_reserved(p, &GEN), "{p}");
        }
        assert!(!writable_overlaps_reserved("/etc", &[]));
    }

    #[test]
    fn description_is_stable() {
        assert_eq!(describe(&GEN), "kiln-protected-paths 1\nmount /\nmount /dev\nmount /dev/null\nmount /dev/zero\n\
            mount /dev/full\nmount /dev/random\nmount /dev/urandom\nmount /dev/tty\nmount /dev/shm\nmount /proc\n\
            mount /sys/fs/cgroup\ntarget /dev\ntarget /proc\ntarget /sys/fs/cgroup\nancestor /\nancestor /sys\n\
            ancestor /sys/fs\ngenerated /etc/resolv.conf\nexcluded /dev\nexcluded /dev/shm\n\
            excluded /etc/resolv.conf\nexcluded /proc\nexcluded /sys/fs/cgroup\n");
    }
}
